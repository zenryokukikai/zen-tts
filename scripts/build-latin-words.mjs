// Builds src/runtime/latin-words.ts: ROMAJI_EXCLUDE, the English words that are not read as romaji (no readings).
// Since 1.2.0 English words are read by the G2P model; the runtime no longer has an English word list. A word is excluded
// from romaji when it parses as romaji but is English:
//   romaji-exclude.txt (CMUdict words whose vowels do not fit the romaji reading, scripts/latin-words/README.md), plus
//   the words of curated.tsv / neologd.tsv / cmu-auto.tsv (the English words the G2P was trained on) whose katakana is not
//   their romaji reading exactly (date デート, not だて; tokyo トーキョー, not ときょ). A listed word whose katakana is its romaji
//   reading (banana バナナ) stays romaji: both give the same sound.
// Usage: npm run build && node scripts/build-latin-words.mjs && npm run build
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const { romajiToHiragana } = await import(path.join(root, 'dist', 'runtime', 'latin-reading.js'));
const dir = path.join(root, 'data', 'latin-words');
const rows = (f) => fs.readFileSync(path.join(dir, f), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
const KATA = /^[ァ-ヴー]+$/;
const WORD = /^[a-z]+(?:[-'][a-z]+)*$/;
const words = new Map();
for (const f of ['cmu-auto.tsv', 'neologd.tsv', 'curated.tsv']) {
  for (const l of rows(f)) {
    const [w0, k] = l.split('\t');
    const w = (w0 ?? '').toLowerCase();
    if (!WORD.test(w) || !k || !KATA.test(k)) throw new Error(`${f}: bad row ${l}`);
    words.set(w, k); // curated wins (read last)
  }
}
const kata = (h) => h.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
const same = (a, b) => a === b; // exact: tokyo トーキョー is not ときょ (the long vowels count)
const exclude = new Set(rows('romaji-exclude.txt').map((w) => w.toLowerCase()));
let added = 0, keptRomaji = 0;
for (const [w, k] of words) {
  const r = romajiToHiragana(w);
  if (!r) continue;
  if (same(kata(r), k)) { exclude.delete(w); keptRomaji++; continue; }
  if (!exclude.has(w)) { exclude.add(w); added++; }
}
const out = `// Generated by scripts/build-latin-words.mjs from data/latin-words/ (do not edit; edit the data files and rebuild).
// Sources and licences: scripts/latin-words/README.md and THIRD_PARTY_NOTICES.md.
/** words not read as romaji (English words that also parse as romaji), one per line (lower case). No readings. */
export const ROMAJI_EXCLUDE = ${JSON.stringify([...exclude].sort().join('\n'))};
`;
fs.writeFileSync(path.join(root, 'src', 'runtime', 'latin-words.ts'), out);
console.log(JSON.stringify({ romajiExclude: exclude.size, addedFromWordList: added, listedWordsKeptAsRomaji: keptRomaji, bytes: Buffer.byteLength(out) }));
